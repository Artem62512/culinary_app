export function detectUnit(productName: string): string {
  const name = productName
    .toLowerCase()
    .replace(/ё/g, 'е')
    .trim();

  // 1. Явно указанная единица в названии имеет приоритет.
  if (/\d+(?:[.,]\d+)?\s*(?:мл|миллилитр(?:а|ов)?)(?:\b|$)/i.test(name)) return 'ml';
  if (/\d+(?:[.,]\d+)?\s*(?:л|литр(?:а|ов)?)(?:\b|$)/i.test(name)) return 'l';
  if (/\d+(?:[.,]\d+)?\s*(?:кг|килограмм(?:а|ов)?)(?:\b|$)/i.test(name)) return 'kg';
  if (/\d+(?:[.,]\d+)?\s*(?:г|гр|грамм(?:а|ов)?)(?:\b|$)/i.test(name)) return 'g';
  if (/\d+(?:[.,]\d+)?\s*(?:шт\.?|штук(?:а|и)?)(?:\b|$)/i.test(name)) return 'pcs';

  // 2. Продукты, которые обычно измеряются в граммах.
  const solidKeywords = [
    'масло сливочное',
    'масло топленое',
    'масло гхи',
    'масло кокосовое',
    'молоко сухое',
    'молоко сгущенное',
    'сливки сухие',
    'сыр',
    'творог',
    'сметана',
    'йогурт густой',
    'паста',
    'томатная паста',
    'пюре',
    'мука',
    'крупа',
    'рис',
    'гречка',
    'овсянка',
    'макароны',
    'спагетти',
    'фарш',
    'говядина',
    'свинина',
    'курица',
    'индейка',
    'мясо',
    'рыба',
    'филе',
    'колбаса',
    'ветчина',
    'бекон',
    'орехи',
    'семечки',
    'сахар',
    'соль',
    'крахмал',
    'какао-порошок',
    'желатин',
    'дрожжи',
    'панировочные сухари',
  ];

  if (solidKeywords.some(keyword => name.includes(keyword))) return 'g';

  // 3. Жидкие продукты.
  const liquidKeywords = [
    'молоко',
    'сливки',
    'кефир',
    'ряженка',
    'айран',
    'тан',
    'кумыс',
    'вода',
    'сок',
    'нектар',
    'морс',
    'компот',
    'чай',
    'кофе',
    'лимонад',
    'квас',
    'масло растительное',
    'масло оливковое',
    'масло подсолнечное',
    'масло льняное',
    'масло кунжутное',
    'масло виноградной косточки',
    'масло авокадо',
    'уксус',
    'бальзамик',
    'сироп',
    'бульон',
    'рассол',
    'маринад',
    'соевый соус',
    'рыбный соус',
    'вустерский соус',
    'тобаско',
    'майонез',
    'меланж',
  ];

  if (liquidKeywords.some(keyword => name.includes(keyword))) return 'ml';

  // 4. Продукты, которые обычно считают поштучно.
  const pieceKeywords = [
    'яйцо',
    'яйца',
    'яиц',
    'лук',
    'луковица',
    'морковь',
    'картофель',
    'картошка',
    'помидор',
    'томат',
    'огурец',
    'перец сладкий',
    'перец болгарский',
    'баклажан',
    'кабачок',
    'свекла',
    'яблоко',
    'банан',
    'апельсин',
    'лимон',
    'груша',
    'авокадо',
    'киви',
    'чеснок',
    'зубчик',
    'лавровый лист',
  ];

  if (pieceKeywords.some(keyword => name.includes(keyword))) return 'pcs';

  // 5. Специи и продукты, обычно измеряемые щепотками/ложками,
  // без явного количества оставляем в граммах.
  return 'g';
}
